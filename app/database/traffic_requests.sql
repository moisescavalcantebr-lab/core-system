CREATE TABLE IF NOT EXISTS content_studio_traffic_requests (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    project_id INT UNSIGNED NOT NULL,
    project_user_id INT UNSIGNED NOT NULL,
    title VARCHAR(160) NOT NULL,
    business_name VARCHAR(160) NOT NULL DEFAULT '',
    contact_name VARCHAR(140) NOT NULL DEFAULT '',
    contact_email VARCHAR(180) NOT NULL DEFAULT '',
    contact_phone VARCHAR(40) NOT NULL DEFAULT '',
    destination_type VARCHAR(20) NOT NULL DEFAULT 'external',
    destination_url VARCHAR(500) NOT NULL DEFAULT '',
    project_page_id INT UNSIGNED NULL,
    page_title VARCHAR(160) NULL,
    platform VARCHAR(20) NOT NULL DEFAULT 'recommend',
    guidance_question TEXT NULL,
    objective VARCHAR(120) NOT NULL DEFAULT '',
    region VARCHAR(180) NOT NULL DEFAULT '',
    audience TEXT NULL,
    language VARCHAR(60) NOT NULL DEFAULT 'Portugues',
    starts_at DATE NULL,
    ends_at DATE NULL,
    materials TEXT NULL,
    notes TEXT NULL,
    authorized_at DATETIME NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'draft',
    conversation_open TINYINT(1) NOT NULL DEFAULT 0,
    revision INT UNSIGNED NOT NULL DEFAULT 1,
    campaign_id INT UNSIGNED NULL,
    submitted_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_traffic_campaign (campaign_id),
    KEY idx_traffic_project (project_id, status),
    KEY idx_traffic_queue (status, submitted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS content_studio_traffic_events (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    request_id INT UNSIGNED NOT NULL,
    actor_type VARCHAR(20) NOT NULL,
    actor_id INT UNSIGNED NOT NULL,
    status VARCHAR(30) NOT NULL,
    message TEXT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_traffic_event_request (request_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
